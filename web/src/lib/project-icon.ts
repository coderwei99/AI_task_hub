export type ParsedIcon = { kind: 'lucide'; name: string } | { kind: 'emoji'; value: string };

export function parseIcon(icon: string): ParsedIcon {
  return icon.startsWith(LUCIDE_ICON_PREFIX)
    ? { kind: 'lucide', name: icon.slice(LUCIDE_ICON_PREFIX.length) }
    : { kind: 'emoji', value: icon };
}

export function lucideIcon(name: string): string {
  return `${LUCIDE_ICON_PREFIX}${name}`;
}
